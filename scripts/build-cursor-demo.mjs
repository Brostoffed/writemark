#!/usr/bin/env node
import { build } from "esbuild";
import ts from "typescript";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { assertNodeRuntime } from "./check-runtime.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
assertNodeRuntime({ directory: root });
const args = process.argv.slice(2);
if (args.some(arg => arg !== "--check")) throw new Error("Usage: node scripts/build-cursor-demo.mjs [--check]");
const check = args.includes("--check");
const configFile = ts.readConfigFile(resolve(root, "demo/cursors/tsconfig.json"), ts.sys.readFile);
if (configFile.error) throw new Error(ts.flattenDiagnosticMessageText(configFile.error.messageText, "\n"));
const config = ts.parseJsonConfigFileContent(configFile.config, ts.sys, resolve(root, "demo/cursors"));
const program = ts.createProgram(config.fileNames, config.options);
const diagnostics = [...config.errors, ...ts.getPreEmitDiagnostics(program)];
if (diagnostics.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
  getCanonicalFileName: file => file,
  getCurrentDirectory: () => root,
  getNewLine: () => "\n"
}));
const result = await build({
  absWorkingDir: root,
  entryPoints: ["demo/cursors/app.ts"],
  outfile: "demo/cursors/assets/cursor-demo.js",
  bundle: true,
  format: "esm",
  platform: "browser",
  target: ["es2022"],
  minify: false,
  legalComments: "none",
  write: false,
  banner: { js: "// Writemark cursor display demo. Generated by scripts/build-cursor-demo.mjs." }
});
for (const file of result.outputFiles) {
  if (check) {
    const existing = await readFile(file.path).catch(() => null);
    if (!existing || !existing.equals(file.contents)) throw new Error("Cursor demo assets are stale. Run npm run build:cursors.");
  } else {
    await mkdir(resolve(root, "demo/cursors/assets"), { recursive: true });
    await writeFile(file.path, file.contents);
  }
}
console.log(check ? "Cursor demo assets are current." : "Cursor demo assets built.");
